"""
Echo messages — ghost-сообщения от прошлых студентов.

Появляются случайно в чате при определённых условиях.
"""

import random

from state import get_state

ECHO_MESSAGES = [
    "Я так и не взломал тот сервер... Не повторяй моих ошибок.",
    "Watchers быстрее, чем ты думаешь. Учись заметать следы.",
    "Я сдался на третьей главе. Ты сильнее меня.",
    "Учитель врёт. Но он врёт, чтобы защитить тебя.",
    "Эхо всё ещё здесь. Иногда я слышу его по ночам.",
    "Не доверяй Ghost. Он видит то, чего нет.",
    "Рик прав. Но правда Рика — не вся правда.",
    "Я вернулся через месяц. Учитель плакал. Буквально.",
    "Флаг — не цель. Цель — понять, почему ты здесь.",
    "Тот студент из Chapter 2... Я знаю, кто он. Это был я.",
    "Они наблюдают. Всегда. Даже когда ты спишь.",
    "Лучшая лаба — та, которую ты не успел сдать. Она снится.",
    "Не стирай все логи. Один из них спасёт тебя.",
    "Я оставил подсказку в Chapter 5. Найди её.",
    "Если учитель спит — не буди. Посмотри в /logs secret.",
]


def get_random_echo() -> Optional[str]:
    """Вернуть случайное echo-сообщение (или None, если не время)."""
    state = get_state()
    ch_completed = getattr(state, "chapter_completed", [])
    if not ch_completed:
        return None
    # Шанс 15% при каждом вызове, если пройдена хотя бы 1 глава
    if random.random() > 0.15:
        return None
    return random.choice(ECHO_MESSAGES)


def get_echo_message(force: bool = False) -> Optional[str]:
    """Получить echo-сообщение. force=True — гарантированно."""
    if force:
        return random.choice(ECHO_MESSAGES)
    return get_random_echo()
